import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright-core')

const BASE = process.argv[2] ?? 'http://localhost:4176'
const OUT = fileURLToPath(new URL('../.agent-out/klickpfad-shots/', import.meta.url)) // fileURLToPath, sonst landen Leerzeichen im Pfad als %20
mkdirSync(OUT, { recursive: true })
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

const results = []
const pageErrors = []
let page
let nShot = 0

async function shot(name) {
  nShot += 1
  await page.screenshot({ path: `${OUT}${String(nShot).padStart(2, '0')}-${name}.png` })
}
async function step(name, fn) {
  try {
    await fn()
    results.push(`ok    ${name}`)
    console.log(`ok    ${name}`)
  } catch (err) {
    results.push(`FAIL  ${name} — ${String(err.message ?? err).split('\n')[0]}`)
    console.log(`FAIL  ${name} — ${String(err.message ?? err).split('\n')[0]}`)
    await shot(`FAIL-${name.replace(/[^a-z0-9]+/gi, '_').slice(0, 40)}`).catch(() => {})
  }
}
/** In-App-Navigation ohne Neuladen (Mock-Zustand bleibt) */
async function go(path) {
  await page.evaluate((p) => { window.history.pushState({}, '', p); window.dispatchEvent(new PopStateEvent('popstate')) }, path)
  await page.waitForTimeout(250)
}
const wait = (ms) => page.waitForTimeout(ms)
async function pickOption(trigger, optionName) {
  await trigger.click()
  await page.getByRole('option', { name: optionName }).first().click()
}
async function expectVisible(locator, what) {
  await locator.first().waitFor({ state: 'visible', timeout: 5000 }).catch(() => { throw new Error(`nicht sichtbar: ${what}`) })
}
async function expectGone(locator, what) {
  await locator.first().waitFor({ state: 'hidden', timeout: 5000 }).catch(() => { throw new Error(`noch sichtbar: ${what}`) })
}
const dialog = () => page.getByRole('dialog')
const rowOf = (text) => page.getByRole('row', { name: new RegExp(text) }).first()
async function rowMenu(text, item) {
  await rowOf(text).getByRole('button', { name: 'Aktionen' }).click()
  await page.getByRole('menuitem', { name: item }).click()
}

const browser = await chromium.launch({ executablePath: CHROME, headless: true })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'de-DE' })
page = await ctx.newPage()
page.on('pageerror', (e) => pageErrors.push(`pageerror: ${e.message}`))
page.on('console', (m) => { if (m.type() === 'error') pageErrors.push(`console.error: ${m.text().slice(0, 200)}`) })

await page.goto(`${BASE}/?demo=admin`)
await page.getByRole('heading', { name: 'Übersicht' }).waitFor()

